# AI_PROVIDER: "gemini" (Google AI Studio, capa gratuita) u "openai".
# La clave se lee de backend/.env y nunca se escribe en el código (SRS 1.4-j).

AI_PROVIDER = env("AI_PROVIDER", default="gemini")
AI_API_KEY = env("AI_API_KEY", default="")

# Los nombres de modelo cambian con el tiempo y los viejos se retiran.
# Si una llamada falla con 403 o 404, revisa qué modelos acepta tu clave:
#   https://generativelanguage.googleapis.com/v1beta/models?key=TU_CLAVE
_DEFAULT_MODELS = {
    "gemini": {"chat": "gemini-3.6-flash", "embedding": "gemini-embedding-001"},
    "openai": {"chat": "gpt-4o-mini", "embedding": "text-embedding-3-small"},
}
_models = _DEFAULT_MODELS.get(AI_PROVIDER, _DEFAULT_MODELS["gemini"])

AI_CHAT_MODEL = env("AI_CHAT_MODEL", default=_models["chat"])
AI_EMBEDDING_MODEL = env("AI_EMBEDDING_MODEL", default=_models["embedding"])

# Tope de tokens de la respuesta. En los modelos Gemini 3.x el
# razonamiento interno se descuenta de aquí, así que conviene holgado.
AI_MAX_OUTPUT_TOKENS = env.int("AI_MAX_OUTPUT_TOKENS", default=2048)

# Cuánto razona el modelo antes de responder: minimal, low, medium o high.
# Solo aplica a los modelos Gemini 3.x. Vacío = no se envía el parámetro.
AI_THINKING_LEVEL = env("AI_THINKING_LEVEL", default="low")

# Cuántos fragmentos se piden por llamada al calcular embeddings.
# Lotes grandes son más rápidos pero chocan antes con el límite por
# minuto del tier gratuito. Bájalo si aparecen errores 429.
