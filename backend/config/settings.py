# Cuántos fragmentos se le pasan al modelo como contexto.
RAG_TOP_K = env.int("RAG_TOP_K", default=4)

# Similitud coseno mínima para considerar que un fragmento responde la
# pregunta. Por debajo de este valor el sistema declara su limitación en
# lugar de responder (US10).
RAG_MIN_RELEVANCE = env.float("RAG_MIN_RELEVANCE", default=0.55)
